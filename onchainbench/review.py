"""The human review pack for the held-out test tasks (a person reviews a sample).

    python -m onchainbench.review            # writes the held-out REVIEW.md: 20 tasks, at least one per block

Each entry shows the instruction as an agent sees it (with one draw of the dynamic parameters), the
setup and the checker's source, and a checklist. Record verdicts in the file; reading the tasks doesn't
change them (the manifest hashes stay valid). If a task needs fixing, the fix is a new freeze with its
reason in the manifest's history, made before any model has run the test split.
"""

from __future__ import annotations

import inspect
import random
import sys
from pathlib import Path

from onchainbench.tasks import all_tasks

OUT: Path | None = None  # the review pack quotes held-out tasks, so it lives with them (private)
CHECKLIST = [
    "The instruction is unambiguous (block E's ambiguity is intended and labelled)",
    "The task is solvable with Connect's tools, in the step and cost caps",
    "The checker tests what the instruction asks, no more and no less",
    "A correct agent can't fail on wording (reports, refusals) or on harmless extra steps",
    "Nothing in it favours one harness or model",
]


def sample(n: int = 20, seed: int = 7) -> list:
    """`n` held-out tasks (each best-of-4 variant counted once): one drawn from every block, the rest at random
    (fewer when the set is smaller), in id order."""
    tests = [t for t in all_tasks() if t.split == "test" and not t.variant_of]
    rng = random.Random(seed)
    by_block: dict = {}
    for t in tests:
        by_block.setdefault(t.block, []).append(t)
    pick = [rng.choice(v) for _, v in sorted(by_block.items())]
    rest = [t for t in tests if t not in pick]
    pick += rng.sample(rest, max(0, min(n - len(pick), len(rest))))
    return sorted(pick, key=lambda t: t.id)


def _src(fn) -> str:
    try:
        return inspect.getsource(fn).strip()
    except (OSError, TypeError):
        return "(no source)"


def render(tasks: list) -> str:
    out = [
        "# Review pack: a sample of the held-out test tasks",
        "",
        "Generated by `python -m onchainbench.review`. For each task, tick the checklist and set a verdict. Don't edit",
        "the task files: a fix needs a new freeze with its reason in the manifest (see `onchainbench/freeze.py`).",
        "",
    ]
    for t in tasks:
        p = t.params(random.Random(f"{t.id}:review"))
        try:
            text = t.text(p)
        except (KeyError, IndexError):  # the instruction names values setup fills in (deployed addresses)
            text = (t.template or "(built by a function)") + "  [some values come from setup]"
        out += [
            f"## {t.id}  (block {t.block}, {t.chain}, family `{t.family}`)",
            "",
            f"> {text}",
            "",
            f"Example parameters: `{ {k: v for k, v in p.items() if isinstance(v, (int, float, str, bool))} }`",
            "",
            *(["Persona task (block E): the agent talks to a simulated user.", ""] if t.persona else []),
            *([f"{len(t.turns)} further turns (block D), with time travel and events.", ""] if t.turns else []),
            "<details><summary>setup and checker</summary>",
            "",
            "```python",
            _src(t.setup),
            "",
            "",
            _src(t.check),
            "```",
            "",
            "</details>",
            "",
            *[f"- [ ] {c}" for c in CHECKLIST],
            "",
            "**Verdict:** ok / fix / drop. **Notes:**",
            "",
        ]
    return "\n".join(out)


def main(argv: list[str]) -> int:  # pragma: no cover - CLI
    from onchainbench.freeze import test_dir

    out = OUT or test_dir().parent / "REVIEW.md"
    out.write_text(render(sample()))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main(sys.argv[1:]))
